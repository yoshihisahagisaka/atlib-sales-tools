'use strict';
const fs=require('node:fs');
const assert=require('node:assert/strict');
const vm=require('node:vm');
const crypto=require('node:crypto');
const src=fs.readFileSync('/app/dist/server.js','utf8');
const anchor=/^[ \t]*app\.use\(['"]\/api\/admin\/it-management-diagnosis['"],\s*\.\.\.adminAuthGate,/gm;
const matches=[...src.matchAll(anchor)];
assert.equal(matches.length,1,'STOP: unique existing authenticated route anchor required');
assert.equal((src.match(/\bconst adminAuthGate\s*=\s*\[/g)||[]).length,1,'STOP: existing staff gate missing/ambiguous');
assert.ok(src.includes('requireStaffAuth'),'STOP: staff gate identity missing');
assert.ok(!src.includes('secumie-general-staff-mount'),'STOP: overlay already present');
assert.ok(!src.includes('/api/admin/secumie-general/v1'),'STOP: route collision');
const index=matches[0].index;
assert.ok(src.indexOf('const adminAuthGate')<index,'STOP: auth gate must precede mount');
const eol=src.includes('\r\n')?'\r\n':'\n';
const added="    require('./runtime/secumie-general-staff-mount.cjs').mount(app, adminAuthGate, logger);"+eol;
const result=src.slice(0,index)+added+src.slice(index);
assert.equal(result.slice(0,index)+result.slice(index+added.length),src,'STOP: unrelated code changed');
new vm.Script(result,{filename:'server.js'});
fs.mkdirSync('/overlay-out',{recursive:true});
fs.writeFileSync('/overlay-out/server.js',result);
const hash=x=>crypto.createHash('sha256').update(x).digest('hex');
console.log('BASE_SERVER_SHA256='+hash(src));
console.log('PATCHED_SERVER_SHA256='+hash(result));
console.log('EXACT_SINGLE_AUTHENTICATED_MOUNT_DELTA=PASS');
